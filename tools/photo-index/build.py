#!/usr/bin/env python3
"""Build photo-index.js: every picture card on the site, keyed by word (letters only, lowercase).
window.PHOTO_INDEX = {word: ["u03/abate", "h05/abate", ...]}  (Barron's u, Must-Know mk, Hot h, VA v order)
app.js photoFor() uses a card's own picture first; if that file doesn't exist it borrows another zone's
picture of the same word. Re-run after adding any images:  python3 tools/photo-index/build.py"""
import os, json, re
R = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
IMG = os.path.join(R, 'images')
rank = {'u': 0, 'mk': 1, 'h': 2, 'v': 3}
idx = {}
for d in sorted(os.listdir(IMG)):
    m = re.match(r'^(u|h|v|mk)(\d*)$', d)
    if not m or not os.path.isdir(os.path.join(IMG, d)): continue
    for f in sorted(os.listdir(os.path.join(IMG, d))):
        if not f.endswith('.webp'): continue
        idx.setdefault(f[:-5], []).append(f'{d}/{f[:-5]}')
for k in idx:
    idx[k].sort(key=lambda p: (rank[re.match(r'[a-z]+', p).group(0) if not p.startswith('mk') else 'mk'], p))
with open(os.path.join(R, 'photo-index.js'), 'w') as fh:
    fh.write('// Auto-generated by tools/photo-index/build.py — every picture card on the site, by word.\n')
    fh.write('window.PHOTO_INDEX = ' + json.dumps(idx, separators=(',', ':')) + ';\n')
print('words with pictures:', len(idx), 'files:', sum(len(v) for v in idx.values()))
