"""Build sat-relations.js: SAT synonyms/antonyms for every card on this site, with links to the target word's own card.

Source: ../../../sat-learning-and-quiz-combined-sources/data/relations/*.json (per word: syn/ant, corpus words only).
Output: sat-relations.js  →  window.SAT_REL = {word: [[synonyms], [antonyms]]}
                             window.SAT_ROOTS = {word: [set, chinese]}  (card location for words that only live in 字根字首 sets)
app.js resolves each word to a card in priority order: Barron's → Hot Words → Verbal Advantage → Must-Know → 字根字首.
Run from the repo root: python3 tools/sat-relations/build.py
"""
import json, re, glob, os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SAT = os.path.join(os.path.dirname(ROOT), 'sat-learning-and-quiz-combined-sources')

def js_obj(path, marker):
    s = open(path, encoding='utf-8').read()
    i = s.index(marker) + len(marker)
    j = s.index('};\n', i) if '};\n' in s[i:] else s.rindex('}')
    return json.loads(s[i:j + 1])

def key(w):
    w = re.sub(r'\(.*?\)', '', str(w)).replace('^', '')
    return re.sub(r'\s+', ' ', w.strip().lower())

barrons = {key(k) for k in js_obj(f'{ROOT}/all-words.js', 'window.BARRONS_INDEX = ')}
hot = {key(k) for k in js_obj(f'{ROOT}/hot-words.js', 'window.HOT_INDEX = ')}
va = {key(k) for k in js_obj(f'{ROOT}/va-words.js', 'window.VA_INDEX = ')}
mk = {key(k) for k in js_obj(f'{ROOT}/mk-words.js', 'window.MK_INDEX = ')}
roots_idx = js_obj(f'{ROOT}/roots-words.js', 'window.ROOTS_INDEX = ')
roots = {key(k): v for k, v in roots_idx.items()}
on_site = barrons | hot | va | mk | set(roots)

pos = {}
for f in glob.glob(f'{SAT}/data/batches/*.json'):
    for w in json.load(open(f, encoding='utf-8'))['words']:
        pos.setdefault(key(w['word']), set()).add(w['pos_key'])

def same_pos_first(k, words, keep=8):
    mine = pos.get(k, set())
    same = [x for x in words if pos.get(x, set()) & mine]
    other = [x for x in words if x not in same]
    out = same if len(same) >= 3 else same + other[:3 - len(same)]
    return out[:keep]

rel = {}
for f in glob.glob(f'{SAT}/data/relations/*.json'):
    for w, r in json.load(open(f, encoding='utf-8')).items():
        k = key(w)
        if k in rel: continue
        syn = [key(x['w']) for x in r.get('syn', [])]
        ant = [key(x['w']) for x in r.get('ant', [])]
        syn = same_pos_first(k, [x for x in dict.fromkeys(syn) if x in on_site and x != k], 8)
        ant = same_pos_first(k, [x for x in dict.fromkeys(ant) if x in on_site and x != k and x not in syn], 6)
        if syn or ant: rel[k] = [syn, ant]

needed = {x for v in rel.values() for lst in v for x in lst}
roots_only = {x: [roots[x][0], roots[x][3]] for x in needed if x not in (barrons | hot | va | mk) and x in roots}
site_words = barrons | hot | va | mk | set(roots)
covered = sum(1 for w in site_words if w in rel)
open(f'{ROOT}/sat-relations.js', 'w', encoding='utf-8').write(
    '// Auto-generated by tools/sat-relations/build.py — SAT synonyms/antonyms (words with a card on this site)\n'
    'window.SAT_REL = ' + json.dumps(rel, ensure_ascii=False, separators=(',', ':')) + ';\n'
    'window.SAT_ROOTS = ' + json.dumps(roots_only, ensure_ascii=False, separators=(',', ':')) + ';\n')
print('relations', len(rel), 'roots-only targets', len(roots_only), 'site words covered', covered, '/', len(site_words))
