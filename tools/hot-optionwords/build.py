"""Add the 教甄 option words (teacher-exam MCQ options not yet on this site) to the Hot Words zone.

Input : src.json  (rows: w, L, pos, d, c, syn, ex, exams, forms; lessons: {n: [theme, themeZh]})
        gen/*.txt (one line per word:  word | 例句中譯 | advanced sentence | 進階例句中譯 [| replacement sentence])
Output: hot-unitN-data.js  - cards with "source": "tk" appended to lessons 1-92 (existing cards untouched,
                             so saved review-list keys h<lesson>:<index> stay valid); lessons 93+ created
        hot-unitN.html     - pages for new lessons 93+
        hot-words.js / hot-dashboard-data.js - regenerated by tools/hot-expand/prune.py
Idempotent: old "tk" cards are removed before adding. Words without a gen/ line are skipped (built later).
Run from the repo root:  python3 tools/hot-optionwords/build.py   (then bump ?v=, see README)
"""
import json, os, re, glob, html, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, HERE)
from blank import blank

A, B = 'window.FLASHCARD_UNITS = ', 'window.LOCAL_LOOKUP = Object.assign({}, window.LOCAL_LOOKUP || {}, '
dec = json.JSONDecoder()
src = json.load(open(f'{HERE}/src.json', encoding='utf-8'))
LES = src['lessons']

gen = {}
for f in sorted(glob.glob(f'{HERE}/gen/*.txt')):
    for ln in open(f, encoding='utf-8'):
        p = [x.strip() for x in ln.rstrip('\n').split(' | ')]
        if len(p) < 4: continue
        gen[p[0]] = {'t': p[1], 's2': p[2], 't2': p[3], 's1': p[4] if len(p) > 4 else None}

def defn(d):
    d = d.strip()
    d = d[:1].upper() + d[1:]
    return d if d.endswith('.') else d + '.'

problems, cards_by_L = [], {}
for r in src['rows']:
    g = gen.get(r['w'])
    if not g: continue
    s1 = g['s1'] or r['ex']
    b = blank(s1, r['w'])
    if not b: problems.append(('blank', r['w'], s1)); continue
    if r['w'].lower() not in g['s2'].lower() and not any(f.lower() in g['s2'].lower() for f in r['forms']):
        problems.append(('s2-missing-word', r['w'], g['s2']))
    d = defn(r['d'])
    cards_by_L.setdefault(r['L'], []).append({
        'word': r['w'], 'pos': r['pos'], 'definition': d, 'chinese': r['c'], 'synonyms': r['syn'], 'image': 'shield',
        'sentence': b, 'translation': g['t'], 'lookup': {'english': d, 'chinese': r['c']},
        'advSentence': g['s2'], 'advTranslation': g['t2'], 'added': True, 'source': 'tk', 'exams': r['exams']})

tmpl = open(f'{ROOT}/hot-unit1.html', encoding='utf-8').read()
s = open(f'{ROOT}/hot-words.js', encoding='utf-8').read()
meta = dec.raw_decode(s, s.index('window.HOT_LESSON_META = ') + len('window.HOT_LESSON_META = '))[0]

maxL = max(int(k) for k in LES)
for L in range(1, maxL + 1):
    path = f'{ROOT}/hot-unit{L}-data.js'
    new = cards_by_L.get(L, [])
    if os.path.exists(path):
        t = open(path, encoding='utf-8').read()
        units, _ = dec.raw_decode(t, t.index(A) + len(A))
        unit = units[str(L)]
        lookup, _ = dec.raw_decode(t, t.index(B) + len(B))
        head = t[:t.index(A)]
    else:
        if not new: continue
        theme, themeZh = LES[str(L)]
        unit = {'title': f'Hot Words for the SAT Lesson {L}: {theme}', 'theme': theme, 'themeZh': themeZh,
                'cards': [], 'group': f'tk-{L}', 'antonymLessons': []}
        lookup, head = {}, ''
    old_tk = {c['word'].lower() for c in unit['cards'] if c.get('source') == 'tk'}
    unit['cards'] = [c for c in unit['cards'] if c.get('source') != 'tk']
    lookup = {k: v for k, v in lookup.items() if k.lower() not in old_tk}
    have = {c['word'].lower() for c in unit['cards']}
    for c in new:
        if c['word'].lower() in have: continue
        unit['cards'].append(c)
        lookup.setdefault(c['word'], [c['definition'], c['chinese']])
    open(path, 'w', encoding='utf-8').write(head + A + json.dumps({str(L): unit}, ensure_ascii=False, indent=2) + ';\n\n'
                                            + B + json.dumps(lookup, ensure_ascii=False, indent=2) + ');\n')
    if L > 92:
        page = f'{ROOT}/hot-unit{L}.html'
        h = (tmpl.replace('Hot Words for the SAT Lesson 1: Brevity and Silence', html.escape(unit['title'], quote=False))
                 .replace('Lesson 1 Flashcards', f'Lesson {L} Flashcards').replace('hot-unit1-data.js', f'hot-unit{L}-data.js'))
        open(page, 'w', encoding='utf-8').write(h)
        meta[str(L)] = {'theme': unit['theme'], 'themeZh': unit['themeZh'], 'antonymLessons': [], 'group': unit['group'],
                        'new': True, 'tk': True, 'words': []}

# write meta (new lessons) back, then let prune.py regenerate HOT_INDEX / words lists / dashboard
i = s.index('window.HOT_LESSON_META = ') + len('window.HOT_LESSON_META = ')
_, j = dec.raw_decode(s, i)
s = s[:i] + json.dumps(meta, ensure_ascii=False) + s[j:]
open(f'{ROOT}/hot-words.js', 'w', encoding='utf-8').write(s)
subprocess.run([sys.executable, f'{ROOT}/tools/hot-expand/prune.py'], check=True, cwd=ROOT)

done = sum(len(v) for v in cards_by_L.values())
print(f'tk cards built: {done} / {len(src["rows"])}; lessons touched: {len(cards_by_L)}')
for p in problems: print('PROBLEM', *p)
