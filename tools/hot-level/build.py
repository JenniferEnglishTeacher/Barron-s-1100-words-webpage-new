#!/usr/bin/env python3
"""Hot Words: split every lesson into 基礎 Core / 進階 Advanced -> hot-levels.js.

Rules (Jennifer, 2026-11-25):
  Lessons 1-35 (book lessons): Core = the book's own Hot Words (cards without "added"); Advanced = ★ added synonyms + ◆ 教甄 words.
  Lessons 36-92 (SAT synonym groups): Core = the group's original SAT words (not "added") + Must-Know 306/386 words
                                       + book Hot Words; Advanced = the later ★/◆ additions.
  Lessons 126+ (hand-built SAT synonym groups, tools/hot-extra): same rule as 36-92.
  Lessons 93-125 (◆ topic lessons): Core = Must-Know / book Hot Words, or everyday-academic words (wordfreq Zipf >= 3.4);
                                     Advanced = the rarer rest.
Only Core words are listed, so a word added to a lesson later is Advanced until this script runs again.
Run after tools/hot-expand/build.py and tools/hot-optionwords/build.py:  python3 tools/hot-level/build.py
(pip install wordfreq). Then bump hot-levels.js?v= in index.html and hot-unit*.html.
"""
import json, os, re, sys
from wordfreq import zipf_frequency

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
ZIPF_CORE = 3.4

def load_units(path):
    s = open(path, encoding="utf8").read()
    i = s.index("window.FLASHCARD_UNITS") ; i = s.index("{", i)
    return json.JSONDecoder().raw_decode(s[i:])[0]

def lesson_count():
    s = open(os.path.join(ROOT, "hot-words.js"), encoding="utf8").read()
    return int(re.search(r"HOT_LESSON_COUNT\s*=\s*(\d+)", s).group(1))

mk = set()
for n in range(1, 31):
    for u in load_units(os.path.join(ROOT, f"mk-unit{n}-data.js")).values():
        mk.update(c["word"].lower() for c in u["cards"])

N = lesson_count()
lessons = {n: list(load_units(os.path.join(ROOT, f"hot-unit{n}-data.js")).values())[0]["cards"] for n in range(1, N + 1)}
book = {c["word"].lower() for n in range(1, 36) for c in lessons[n] if not c.get("added")}
_s = open(os.path.join(ROOT, "hot-words.js"), encoding="utf8").read()
_meta = json.JSONDecoder().raw_decode(_s[_s.index("{", _s.index("window.HOT_LESSON_META")):])[0]
# hand-built SAT synonym-group lessons (tools/hot-extra, 126+) follow the lessons 36-92 rule
SYN_GROUP = {int(k) for k, m in _meta.items() if int(k) > 125 and str(m.get("group", "")).startswith("sat-")}

core, stats = {}, {"core": 0, "adv": 0}
for n, cards in lessons.items():
    keep = []
    for c in cards:
        w = c["word"].lower()
        if n <= 35:
            ok = not c.get("added")
        elif n <= 92 or n in SYN_GROUP:
            ok = not c.get("added") or w in mk or w in book
        else:
            ok = w in mk or w in book or zipf_frequency(w, "en") >= ZIPF_CORE
        if ok:
            keep.append(c["word"])
    core[str(n)] = keep
    stats["core"] += len(keep); stats["adv"] += len(cards) - len(keep)

out = ("// Auto-generated by tools/hot-level/build.py — Hot Words 基礎 Core words per lesson (every other card is 進階 Advanced)\n"
       f"window.HOT_CORE = {json.dumps(core, ensure_ascii=False, separators=(',', ':'))};\n")
open(os.path.join(ROOT, "hot-levels.js"), "w", encoding="utf8").write(out)
print(N, "lessons", stats)

# ---------- per-level MCQ choices -> hot-mcq.js ----------
# Every card's dSAT sentence already has a blank. Every card gets 3 wrong choices: same part of speech, same level where possible, never from the same lesson or
# its antonym lessons, never a listed synonym/antonym or a word sharing a Chinese gloss, and a/an-safe.
import random
s = open(os.path.join(ROOT, "sat-relations.js"), encoding="utf8").read()
i = s.index("{", s.index("window.SAT_REL")); REL = json.JSONDecoder().raw_decode(s[i:])[0]
s = open(os.path.join(ROOT, "hot-words.js"), encoding="utf8").read()
i = s.index("{", s.index("window.HOT_LESSON_META")); META = json.JSONDecoder().raw_decode(s[i:])[0]

def pos_tags(p): return [t.strip().rstrip(".").replace("vb", "v") for t in re.split(r"[/,]", p or "") if t.strip()]
def glosses(z): return {g.strip() for g in re.split(r"[；;／/、,，()（）]", z or "") if len(g.strip()) >= 2}
def vowel(w): return w[:1].lower() in "aeiou"

core_sets = {n: {w.lower() for w in core[str(n)]} for n in lessons}
pool = []
for n, cards in lessons.items():
    for c in cards:
        w = c["word"].lower()
        pool.append({"w": c["word"], "k": w, "n": n, "pos": pos_tags(c["pos"]), "zh": glosses(c["chinese"]),
                     "lv": 1 if w in core_sets[n] else 2})
by_key = {}
for p in pool: by_key.setdefault(p["k"], p)

opts, made, short = {}, 0, []
for n, cards in lessons.items():
    away = {n, *META.get(str(n), {}).get("antonymLessons", [])}
    away |= {int(L) for L, m in META.items() if n in m.get("antonymLessons", [])}
    away |= set(META.get(str(n), {}).get("mcqAvoid", []))
    away |= {int(L) for L, m in META.items() if n in m.get("mcqAvoid", [])}
    lo = {}
    for c in cards:
        w = c["word"].lower()
        me = next(p for p in pool if p["n"] == n and p["k"] == w)
        bad = {w, *REL.get(w, [[], []])[0], *REL.get(w, [[], []])[1],
               *[x.strip().lower() for x in (c.get("synonyms") or "").split(",")]}
        m = re.search(r"\b(a|an)\s+_{3,}", c["sentence"], re.I)
        art = m.group(1).lower() if m else None
        rnd = random.Random(f"{n}:{w}")
        def fits(p, same_pos_exact):
            if p["n"] in away or p["k"] in bad or w in REL.get(p["k"], [[], []])[0]: return False
            if (" " in p["k"]) != (" " in w) or "-" in p["k"] and "-" not in w: return False
            if same_pos_exact and p["pos"] != me["pos"]: return False
            if not same_pos_exact and (not p["pos"] or p["pos"][0] != me["pos"][0] or len(p["pos"]) > 1): return False
            if p["zh"] & me["zh"]: return False
            if art and vowel(p["k"]) != vowel(w): return False
            return True
        cands = [p for p in pool if p["k"] != w]
        rnd.shuffle(cands)
        pick, seen = [], set()
        for exact in (True, False):
            for want_lv in (me["lv"], None):
                for p in cands:
                    if len(pick) == 3: break
                    if p["k"] in seen or (want_lv and p["lv"] != want_lv) or not fits(p, exact): continue
                    seen.add(p["k"]); pick.append(p["w"])
        if len(pick) < 3: short.append((n, w)); continue
        lo[c["word"]] = pick; made += 1
    opts[str(n)] = lo

out = ("// Auto-generated by tools/hot-level/build.py — wrong choices for the Hot Words per-level MCQ (word -> 3 distractors)\n"
       f"window.HOT_MCQ = {json.dumps(opts, ensure_ascii=False, separators=(',', ':'))};\n")
open(os.path.join(ROOT, "hot-mcq.js"), "w", encoding="utf8").write(out)
print("MCQ questions", made, "skipped (too few choices)", len(short), short[:10])
